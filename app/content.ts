export function scoreQuiz(answers: number[]) {
  if (
    answers.length !== 5 ||
    answers.some((a) => !Number.isInteger(a) || a < 0 || a > 3)
  )
    return null;
  const scores = [0, 0, 0, 0];
  answers.slice(0, 4).forEach((a) => scores[a]++);
  const highest = Math.max(...scores);
  const winner = scores.indexOf(highest);
  const secondary = scores
    .map((score, index) => ({ score, index }))
    .filter((x) => x.index !== winner && x.score > 0)
    .sort((a, b) => b.score - a.score || a.index - b.index)[0]?.index;
  return {
    winner,
    tied: scores.filter((s) => s === highest).length > 1,
    goal: answers[4],
    secondary,
  };
}
